export function translate(language: Language, key: TranslationKey): string {
  return (language === 'es' ? spanish[key] : undefined) || english[key];
}

// Storage can be unavailable in privacy modes. Language switching still works.
export function readLanguage(storage?: Pick<Storage, 'getItem'>): Language {
  try {
    const value = (storage ?? window.localStorage).getItem(LANGUAGE_STORAGE_KEY);
    return value === 'es' || value === 'en' ? value : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function persistLanguage(language: Language, storage?: Pick<Storage, 'setItem'>): void {
  try {
    (storage ?? window.localStorage).setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Keep the current selection in memory when persistence is unavailable.
  }
}

export function formatDate(date: string, language: Language): string {
  return new Date(date + 'T12:00:00').toLocaleDateString(locales[language], { month: 'short', day: 'numeric' });
}
